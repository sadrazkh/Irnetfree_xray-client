'use strict';
/**
 * Writes Android's copy of the server editor's field table —
 * android/app/src/main/java/com/irnetfree/vpn/core/ServerFieldsTable.kt — from
 * src/renderer/serverFields.js and the English and Persian strings of
 * src/renderer/i18n.js (Android's I18n reads the Persian while the app is in Persian).
 * One table, two languages of code: Android never edits it by hand, and
 * tests/serverFieldsAndroid.test.js fails when the file is not what this writes.
 *
 *   node scripts/gen-android-server-fields.js          → writes the file
 *   node scripts/gen-android-server-fields.js --check  → exit 1 when it is stale
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const SF = require('../src/renderer/serverFields');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'android', 'app', 'src', 'main', 'java', 'com', 'irnetfree', 'vpn', 'core', 'ServerFieldsTable.kt');

/** One language's table of i18n.js ('en' or 'fa'). */
function strings(lang) {
  const src = fs.readFileSync(path.join(ROOT, 'src', 'renderer', 'i18n.js'), 'utf8');
  const ctx = { window: {}, document: { documentElement: {}, querySelectorAll: () => [] } };
  vm.runInNewContext(src, ctx);
  ctx.window.i18n.applyI18n(lang);
  return (k) => ctx.window.i18n.t(k);
}

/** The English table of i18n.js. */
function english() {
  return strings('en');
}

const kstr = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$').replace(/\n/g, '\\n') + '"';
const klist = (a) => (a ? `listOf(${a.map(kstr).join(', ')})` : 'null');
const kany = (v) => (v === undefined ? 'null' : typeof v === 'number' ? String(v) : kstr(v));

function render() {
  const t = english();
  const fields = SF.FIELDS.map((f) => {
    const w = f.when || {};
    return `        SfField(${[
      `id = ${kstr(f.id)}`, `tab = ${kstr(f.tab)}`, `kind = ${kstr(f.kind)}`,
      `path = ${f.path ? kstr(f.path) : 'null'}`, `special = ${!!f.special}`, `key = ${kstr(f.key)}`,
      `protocols = ${klist(w.protocols)}`, `networks = ${klist(w.networks)}`, `securities = ${klist(w.securities)}`,
      `local = ${!!f.local}`, `simple = ${!!f.simple}`, `span2 = ${f.span === 2}`, `group = ${f.group ? kstr(f.group) : 'null'}`,
      `options = ${f.options ? `listOf(${f.options.map(kstr).join(', ')})` : 'emptyList()'}`,
      `optionLabels = ${kstr(f.optionLabels === true ? 'empty' : f.optionLabels || '')}`,
      `emptyAs = ${kany(f.emptyAs)}`, `hint = ${!!f.hint}`, `placeholder = ${kstr(f.placeholder || '')}`
    ].join(', ')})`;
  });
  // every English string the Android editor shows, by its i18n key
  const keys = new Set();
  for (const f of SF.FIELDS) {
    keys.add('sf.' + f.id);
    for (const sub of [...SF.PROTOCOLS, ...SF.NETWORKS]) if (t(`sf.${f.id}.${sub}`) !== `sf.${f.id}.${sub}`) keys.add(`sf.${f.id}.${sub}`);
    if (f.hint) keys.add(`sf.${f.id}.hint`);
    // a hint by protocol, before the table's own (app.js fieldHint): TUIC's and AnyTLS's pin, core, insecure
    for (const p of SF.PROTOCOLS) if (t(`sf.${f.id}.hint.${p}`) !== `sf.${f.id}.hint.${p}`) keys.add(`sf.${f.id}.hint.${p}`);
    if (f.group) keys.add('sfg.' + f.group);
    if (f.optionLabels) for (const o of f.options) if (f.optionLabels === 'all' || !o) keys.add(`sfo.${f.id}.${o || '_'}`);
  }
  for (const n of SF.NETWORKS) keys.add('sfo.network.' + n);
  for (const s of ['none', 'tls', 'reality']) keys.add('sfo.security.' + s);
  for (const p of SF.PROTOCOLS) keys.add('sfp.' + p);
  for (const tab of SF.TABS) keys.add('edit.tab.' + tab);
  for (const k of ['sf.encryptionValue', 'sfo.encMode.none', 'sfo.encMode.mlkem', 'edit.enc.auth', 'edit.enc.pq', 'edit.enc.mode', 'edit.enc.padding',
    'edit.err.number', 'edit.err.range', 'edit.err.json', 'edit.err.encPrefix', 'edit.err.encMode', 'edit.err.encRtt', 'edit.err.encKey',
    'edit.err.required', 'edit.err.in', 'edit.view.simple', 'edit.view.pro', 'edit.local', 'edit.localNote', 'edit.newTitle', 'btn.addManual',
    'edit.protoFixed', 'edit.protoPick', 'edit.noTransport', 'edit.noSecurity', 'edit.noTls', 'edit.genUuid', 't.serverCreated']) keys.add(k);
  const labels = [...keys].sort().map((k) => {
    const v = t(k);
    if (v === k) throw new Error('no English string for ' + k);
    return `        ${kstr(k)} to ${kstr(v)}`;
  });
  // the same keys in Persian (Android's I18n reads them in Persian); a key the Persian table lacks keeps its English
  const fa = strings('fa');
  const persian = [...keys].sort().map((k) => {
    const v = fa(k);
    return `        ${kstr(k)} to ${kstr(v === k ? t(k) : v)}`;
  });
  return [
    '// GENERATED by scripts/gen-android-server-fields.js from src/renderer/serverFields.js',
    '// and the English and Persian strings of src/renderer/i18n.js. Do not edit by hand:',
    '// tests/serverFieldsAndroid.test.js fails when this file is not what it writes.',
    'package com.irnetfree.vpn.core',
    '',
    '/** The server editor\'s field table (the desktop\'s serverFields.js) and its strings, English and Persian. */',
    'internal object ServerFieldsTable {',
    '    val FIELDS: List<SfField> = listOf(',
    fields.join(',\n'),
    '    )',
    '',
    '    val STRINGS: Map<String, String> = mapOf(',
    labels.join(',\n'),
    '    )',
    '',
    '    /** The same keys in Persian (the desktop\'s fa table): I18n.word reads them while the app is in Persian. */',
    '    val STRINGS_FA: Map<String, String> = mapOf(',
    persian.join(',\n'),
    '    )',
    '}',
    ''
  ].join('\n');
}

if (require.main === module) {
  const text = render();
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (now !== text) { console.error(OUT + ' is stale: run node scripts/gen-android-server-fields.js'); process.exit(1); }
    console.log('ServerFieldsTable.kt is current');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('wrote ' + path.relative(ROOT, OUT) + ` (${SF.FIELDS.length} fields)`);
  }
}
module.exports = { render, OUT };
